/** Legend glyph SVG markup (centered at 0,0 inside a viewBox). */
export function glyph(kind, size = 16, stroke = 1.5) {
  const s = size / 2;
  const st = `stroke="var(--ink)" stroke-width="${stroke}" vector-effect="non-scaling-stroke"`;
  let shape = "";
  switch (kind) {
    case "post":
      shape = `<rect x="${-s * 1.6}" y="${-s * 0.8}" width="${s * 3.2}" height="${s * 1.6}" rx="${s * 0.8}" fill="var(--accent)" ${st}/>`;
      break;
    case "incoming":
      shape = `<circle r="${s * 0.85}" fill="var(--surface)" ${st}/>`;
      break;
    case "automation":
      shape = `<rect x="${-s * 0.72}" y="${-s * 0.72}" width="${s * 1.44}" height="${s * 1.44}" transform="rotate(45)" fill="var(--pop3)" ${st}/>`;
      break;
    case "agent":
      shape = `<circle r="${s * 0.85}" fill="var(--pop2)" ${st}/>`;
      break;
    case "team":
      shape = `<rect x="${-s * 0.8}" y="${-s * 0.8}" width="${s * 1.6}" height="${s * 1.6}" rx="${s * 0.35}" fill="var(--ink)" ${st}/>`;
      break;
    case "attention":
      shape = `<path d="M0 ${-s} L${s * 0.95} ${s * 0.75} L${-s * 0.95} ${s * 0.75}Z" fill="var(--pop1)" stroke-linejoin="round" ${st}/>`;
      break;
  }
  const w = kind === "post" ? size * 1.8 : size;
  const pad = stroke * 2;
  return `<svg class="glyph" width="${w + pad}" height="${size + pad}" viewBox="${-(w + pad) / 2} ${-(size + pad) / 2} ${w + pad} ${size + pad}" aria-hidden="true">${shape}</svg>`;
}

