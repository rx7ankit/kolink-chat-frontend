/** Brand-colored glyph (Instagram and Messenger get their gradient as an SVG fill). */
export function icon(id, size = 24, { mono = false, white = false } = {}) {
  const pl = platforms[id];
  let fill = mono ? "currentColor" : white ? "#fff" : pl.color;
  let defs = "";
  if (!mono && !white && id === "instagram") {
    const g = `ig${gid++}`;
    defs = `<defs><radialGradient id="${g}" cx="0.28" cy="1.05" r="1.25"><stop offset="0" stop-color="#FEDA75"/><stop offset="0.22" stop-color="#FA7E1E"/><stop offset="0.45" stop-color="#D62976"/><stop offset="0.72" stop-color="#962FBF"/><stop offset="1" stop-color="#4F5BD5"/></radialGradient></defs>`;
    fill = `url(#${g})`;
  } else if (!mono && !white && id === "messenger") {
    const g = `ms${gid++}`;
    defs = `<defs><radialGradient id="${g}" cx="0.2" cy="1" r="1.2"><stop offset="0" stop-color="#0099FF"/><stop offset="0.6" stop-color="#A033FF"/><stop offset="0.9" stop-color="#FF5280"/><stop offset="1" stop-color="#FF7061"/></radialGradient></defs>`;
    fill = `url(#${g})`;
  }
  return `<svg class="pi" viewBox="0 0 24 24" width="${size}" height="${size}" aria-hidden="true">${defs}<path d="${pl.path}" fill="${fill}"/></svg>`;
}

/** Rounded tile with a white mark (brand gradient for IG/Messenger). */
